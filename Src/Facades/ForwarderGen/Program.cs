using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;

// Writes [assembly: TypeForwardedTo] attributes for the public top-level types of the given
// implementation assemblies, so a facade answers for every type WPR implements without a list
// to keep in step. Run by Forwarders.targets before a facade compiles.
//
//   ForwarderGen --out <file.cs> (--from <dll> | --fromlist <file of dll paths>)...
//                [--only <assembly name>]... [--ns <namespace prefix>]... [--type <full name>]...
//
// --only keeps just the named assemblies out of --from/--fromlist (a build hands over every
// reference). A type is forwarded when its namespace starts with one of the --ns prefixes (a
// prefix matches the namespace itself and its children) or its full name is one of the --type
// entries.
var froms = new List<string>();
var only = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
var prefixes = new List<string>();
var types = new HashSet<string>(StringComparer.Ordinal);
string? output = null;
for (int i = 0; i + 1 < args.Length; i += 2)
{
    switch (args[i])
    {
        case "--out": output = args[i + 1]; break;
        case "--from": froms.Add(args[i + 1]); break;
        case "--fromlist": froms.AddRange(File.ReadAllLines(args[i + 1]).Where(l => l.Length > 0)); break;
        case "--only": only.Add(args[i + 1]); break;
        case "--ns": prefixes.Add(args[i + 1]); break;
        case "--type": types.Add(args[i + 1]); break;
        default: Console.Error.WriteLine($"ForwarderGen: unknown argument {args[i]}"); return 2;
    }
}
if (only.Count > 0)
    froms = froms.Where(f => only.Contains(Path.GetFileNameWithoutExtension(f))).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
var missing = only.Where(o => !froms.Any(f => string.Equals(Path.GetFileNameWithoutExtension(f), o, StringComparison.OrdinalIgnoreCase))).ToList();
if (missing.Count > 0)
{
    Console.Error.WriteLine($"ForwarderGen: error: not among the references: {string.Join(", ", missing)}");
    return 1;
}
if (output == null || froms.Count == 0)
{
    Console.Error.WriteLine("usage: ForwarderGen --out <file.cs> --from <dll>... [--ns <prefix>]... [--type <full name>]...");
    return 2;
}

bool Wanted(string ns, string fullName) =>
    types.Contains(fullName) || prefixes.Any(p => ns == p || ns.StartsWith(p + ".", StringComparison.Ordinal));

var lines = new SortedSet<string>(StringComparer.Ordinal);
foreach (var path in froms)
{
    using var pe = new PEReader(File.OpenRead(path));
    var md = pe.GetMetadataReader();
    string asm = md.GetString(md.GetAssemblyDefinition().Name);
    foreach (var handle in md.TypeDefinitions)
    {
        var t = md.GetTypeDefinition(handle);
        if ((t.Attributes & TypeAttributes.VisibilityMask) != TypeAttributes.Public) continue;
        string ns = md.GetString(t.Namespace);
        string name = md.GetString(t.Name);
        if (!Wanted(ns, ns + "." + name)) continue;
        int tick = name.IndexOf('`');
        if (tick >= 0) name = name[..tick] + "<" + new string(',', int.Parse(name[(tick + 1)..]) - 1) + ">";
        lines.Add($"[assembly: TypeForwardedTo(typeof(global::{ns}.{name}))] // {asm}");
    }
}

var text = new StringBuilder()
    .AppendLine("// <auto-generated> by Src/Facades/ForwarderGen. Do not edit. </auto-generated>")
    .AppendLine("using System.Runtime.CompilerServices;")
    .AppendLine();
foreach (var l in lines) text.AppendLine(l);
Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
// Rewrite only on change, so an unchanged list does not force the facade to recompile.
if (!File.Exists(output) || File.ReadAllText(output) != text.ToString())
    File.WriteAllText(output, text.ToString());
Console.WriteLine($"ForwarderGen: {lines.Count} forwarders -> {output}");
return 0;
