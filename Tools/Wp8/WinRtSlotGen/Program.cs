using System.Text;
using WPR.Wp8Native;

// Writes WinRtSystemInterfaces.g.cs from Windows' own WinRT metadata. See the csproj for why.
//
// Modern metadata is a valid source for WP8: a WinRT interface is immutable once published (a
// change is a new interface - ICoreWindow2, ICoreWindow3 - with a new IID), so ICoreWindow's
// layout on this machine is the layout a 2012 phone shipped. The runtime checks that against the
// slots it had already confirmed by observation (WinRtSystemInterfaces.Verify).

string metadataDir = args.Length > 0 ? args[0] : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows), "System32", "WinMetadata");
string output = args.Length > 1 ? args[1] : Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "..", "..", "Src", "Engine", "WPR.Engine.Wp8Native", "Runtime", "WinRtSystemInterfaces.g.cs"));

// The Windows Phone Runtime API surface, by namespace. Exact matches: a prefix would pull in
// the whole of Windows.UI.Xaml and Windows.Media, neither of which a WP8 native title has.
HashSet<string> namespaces = new(StringComparer.Ordinal)
{
    "Windows.ApplicationModel",
    "Windows.ApplicationModel.Activation",
    "Windows.ApplicationModel.Core",
    "Windows.ApplicationModel.Store",
    "Windows.Devices.Geolocation",
    "Windows.Devices.Input",
    "Windows.Devices.Sensors",
    "Windows.Foundation",
    "Windows.Foundation.Collections",
    "Windows.Globalization",
    "Windows.Graphics.Display",
    "Windows.Networking",
    "Windows.Networking.Connectivity",
    "Windows.Networking.Sockets",
    "Windows.Storage",
    "Windows.Storage.Streams",
    "Windows.System",
    "Windows.System.Threading",
    "Windows.UI",
    "Windows.UI.Core",
    "Windows.UI.Input",
};

string[] files = Directory.GetFiles(metadataDir, "*.winmd");
WinmdReader reader = WinmdReader.Load(files);

List<WinmdReader.InterfaceLayout> selected = reader.InterfaceNames
    .Where(n => namespaces.Contains(n[..n.LastIndexOf('.')]))
    .Select(n => reader.Interface(n)!)
    .Where(l => l.Iid is not null)
    .OrderBy(l => l.FullName, StringComparer.Ordinal)
    .ToList();

StringBuilder sb = new();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Generated by Tools/Wp8/WinRtSlotGen from Windows' WinRT metadata. Do not edit.");
sb.AppendLine($"// {selected.Count} interfaces from {files.Length} metadata files.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("#nullable enable");
sb.AppendLine("namespace WPR.Wp8Native");
sb.AppendLine("{");
sb.AppendLine("    public static partial class WinRtSystemInterfaces");
sb.AppendLine("    {");
sb.AppendLine("        // Full name, IID, then one entry per method after IInspectable's six slots, in vtable order:");
sb.AppendLine("        // \"Name(ParamType, ...) : ReturnType\". A non-void return is the ABI's trailing out pointer.");
sb.AppendLine("        private static readonly (string Name, string Iid, string[] Methods)[] Table =");
sb.AppendLine("        [");
foreach (WinmdReader.InterfaceLayout layout in selected)
{
    sb.Append("            (\"").Append(layout.FullName).Append("\", \"").Append(layout.Iid!.Value.ToString("D")).Append("\", [");
    sb.Append(string.Join(", ", layout.Methods.Select(m =>
        "\"" + m.Name + "(" + string.Join(", ", m.ParameterTypes) + ") : " + m.ReturnType + "\"")));
    sb.AppendLine("]),");
}

sb.AppendLine("        ];");
sb.AppendLine();

// Every named type those signatures reach, with what the ABI needs to know about it: whether it
// travels as a pointer (interface, class, delegate), a 32-bit enum, or a struct by value - and
// for a struct its size, alignment, and whether it is a homogeneous float aggregate, which
// AAPCS-VFP passes in s/d registers rather than core ones.
TypeIndex index = new(files);
SortedDictionary<string, TypeIndex.Shape> shapes = new(StringComparer.Ordinal);
foreach (WinmdReader.InterfaceLayout layout in selected)
{
    foreach (WinmdReader.MethodLayout method in layout.Methods)
    {
        foreach (string type in method.ParameterTypes.Append(method.ReturnType))
        {
            index.Collect(type, shapes);
        }
    }
}

sb.AppendLine("        // Name, kind (I interface, C runtime class, D delegate, E enum, S struct), size, alignment,");
sb.AppendLine("        // and for a struct of only Single or only Double fields (at most four) the field count, else 0.");
sb.AppendLine("        private static readonly (string Name, char Kind, int Size, int Align, int Hfa)[] TypeTable =");
sb.AppendLine("        [");
foreach ((string name, TypeIndex.Shape shape) in shapes)
{
    sb.AppendLine($"            (\"{name}\", '{shape.Kind}', {shape.Size}, {shape.Align}, {shape.Hfa}),");
}

sb.AppendLine("        ];");
sb.AppendLine("    }");
sb.AppendLine("}");

File.WriteAllText(output, sb.ToString().Replace("\r\n", "\n").Replace("\n", "\r\n"), new UTF8Encoding(false));
Console.WriteLine($"{selected.Count} interfaces, {shapes.Count} types -> {output} ({new FileInfo(output).Length:N0} bytes)");
